package com.viaversion.viafabricplus.injection.mixin.features.v1_16_4.network

import com.viaversion.viafabricplus.util.uninitialized

import org.spongepowered.asm.mixin.Mixin
import org.spongepowered.asm.mixin.Final
import org.spongepowered.asm.mixin.injection.Inject
import org.spongepowered.asm.mixin.injection.At
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo

@Mixin(net.minecraft.client.multiplayer.ClientCommonPacketListenerImpl::class) 
abstract class MixinClientCommonPacketListenerImpl {

    @org.spongepowered.asm.mixin.Shadow @Final 
    @JvmField var minecraft: net.minecraft.client.Minecraft = uninitialized()
    @Inject(method = ["handlePing"], at = [At(value = "INVOKE", target = "Lnet/minecraft/network/protocol/PacketUtils;ensureRunningOnSameThread(Lnet/minecraft/network/protocol/Packet;Lnet/minecraft/network/PacketListener;Lnet/minecraft/network/PacketProcessor;)V", shift = At.Shift.AFTER)], cancellable = true) private fun addMissingConditions(packet: net.minecraft.network.protocol.common.ClientboundPingPacket, ci: CallbackInfo) {
        if (com.viaversion.viafabricplus.ViaFabricPlus.api().targetVersion().olderThanOrEqualTo(com.viaversion.viaversion.api.protocol.version.ProtocolVersion.v1_16_4)) {
            val inventoryId: kotlin.Short = ((packet.getId() shr 16) and 0xFF).toShort()
            if (inventoryId.toInt() != 0 && inventoryId.toInt() != minecraft.player.containerMenu.containerId) {
                ci.cancel()
            }
        }
    }
    
}
