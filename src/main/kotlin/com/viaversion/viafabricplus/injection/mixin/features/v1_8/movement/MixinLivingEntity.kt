package com.viaversion.viafabricplus.injection.mixin.features.v1_8.movement

import org.spongepowered.asm.mixin.Mixin
import org.spongepowered.asm.mixin.injection.Inject
import org.spongepowered.asm.mixin.injection.At
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable
import org.spongepowered.asm.mixin.injection.ModifyConstant

@Mixin(net.minecraft.world.entity.LivingEntity::class) 
abstract class MixinLivingEntity {

    @Inject(method = ["pushEntities"], at = [At("HEAD")], cancellable = true) private fun preventEntityPush(ci: CallbackInfo) {
        if (com.viaversion.viafabricplus.ViaFabricPlus.api().targetVersion().olderThanOrEqualTo(com.viaversion.viaversion.api.protocol.version.ProtocolVersion.v1_8)) {
            ci.cancel()
        }
    }
    
    @Inject(method = ["trapdoorUsableAsLadder"], at = [At("HEAD")], cancellable = true) private fun disableCrawling(ci: CallbackInfoReturnable<kotlin.Boolean>) {
        if (com.viaversion.viafabricplus.ViaFabricPlus.api().targetVersion().olderThanOrEqualTo(com.viaversion.viaversion.api.protocol.version.ProtocolVersion.v1_8)) {
            ci.setReturnValue(false)
        }
    }
    
    @ModifyConstant(method = ["aiStep"], constant = [org.spongepowered.asm.mixin.injection.Constant(doubleValue = 0.003)]) private fun modifyVelocityZero(constant: kotlin.Double): kotlin.Double {
        if (com.viaversion.viafabricplus.ViaFabricPlus.api().targetVersion().olderThanOrEqualTo(com.viaversion.viaversion.api.protocol.version.ProtocolVersion.v1_8)) {
            return 0.005
        } else {
            return constant
        }
    }
    
}
