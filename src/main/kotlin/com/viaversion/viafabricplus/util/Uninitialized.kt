package com.viaversion.viafabricplus.util

import com.viaversion.viafabricplus.util.uninitialized

/**
 * Returns null as an erased generic value. Mixin fields are populated by the
 * target class, so initialising them with this keeps their Kotlin type non-null
 * without running an initialiser in the mixin constructor.
 */
@Suppress("UNCHECKED_CAST")
fun <T> uninitialized(): T = null as T
